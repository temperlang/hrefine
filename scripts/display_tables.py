"""Writes src/display-tables.temper.md, the Unicode data that showing a
domain in Unicode needs, from the files scripts/unicode_data.py gets and
pins.

    uv run scripts/display_tables.py

For now that's one table: the Latin letters, as ranges of code points.
UnicodeData.txt has no Script property, so a Latin letter here is one whose
general category is a letter (L*) and whose name starts with "LATIN ", which
leaves out a few Latin letters (such as the modifier letters and the
ordinal indicators), never adds one from another script, and so only makes
display keep `xn--` more often. Nor is IdentifierStatus.txt pinned, so only
letters in the blocks of modern European and Vietnamese letters count
(`ALLOWED`), where UTS #39 allows nearly all, leaving out IPA, phonetic,
and historic letters, which it restricts and browsers show as `xn--`.
Once Scripts.txt and IdentifierStatus.txt are pinned too, this script
should write the Script property and the identifier status instead (see
docs/plan.md, "Display formatting").
"""

import sys
import textwrap
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import unicode_data  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "display-tables.temper.md"


# Latin-1 Supplement, Latin Extended-A, and Latin Extended Additional but
# its historic letters; and from Latin Extended-B, only Vietnamese o and u
# with horn, Pinyin's vowels with caron and diaeresis, and Romanian s and t
# with comma below. The schwa, for Azerbaijani, is allowed only in .az, in
# display.temper.md.
ALLOWED = [
    (0x00C0, 0x017F),
    (0x01A0, 0x01A1), (0x01AF, 0x01B0), (0x01CD, 0x01DC), (0x0218, 0x021B),
    (0x0259, 0x0259),
    (0x1E00, 0x1E99), (0x1EA0, 0x1EF9),
]


def latin_letters(folder: Path) -> list[int]:
    letters = []
    for line in (folder / "UnicodeData.txt").read_text(encoding="utf-8").splitlines():
        f = line.split(";")
        c = int(f[0], 16)
        # Ranges (<CJK Ideograph, First> and the like) are never Latin.
        allowed = any(a <= c <= b for a, b in ALLOWED)
        if allowed and f[2].startswith("L") and f[1].startswith("LATIN "):
            letters.append(c)
    return letters


def ranges(codes: list[int]) -> list[tuple[int, int]]:
    out: list[list[int]] = []
    for c in codes:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return [(a, b) for a, b in out]


def main() -> None:
    folder = unicode_data.ensure()
    found = ranges(latin_letters(folder))
    # Spot checks: ü, ß, ș, and ệ are in; Cyrillic а, Greek α, ª, IPA ɐ,
    # and small capital ᴏ aren't.
    def has(c: int) -> bool:
        return any(a <= c <= b for a, b in found)
    assert has(0xFC) and has(0xDF) and has(0x0131) and has(0x0219) and has(0x1EC7)
    assert not has(0x0430) and not has(0x03B1) and not has(0xAA)
    assert not has(0x0250) and not has(0x1D0F) and not has(0xD7) and not has(0xF7)
    numbers = ", ".join(f"0x{a:X}, 0x{b:X}" for a, b in found)
    body = "\n".join(textwrap.wrap(numbers, 84, initial_indent="      ", subsequent_indent="      "))
    OUT.write_text(f"""# Display Tables

Generated by `scripts/display_tables.py` from Unicode
{unicode_data.VERSION}'s `UnicodeData.txt`; don't edit by hand.

The Latin letters beyond ASCII, as pairs of first and last code points,
in order: letters (general category L) named `LATIN …`, in the blocks of
modern European and Vietnamese letters, a subset of Unicode's Latin script
(see the script for why).

    let latinLetterRanges: List<Int> = [
{body}
    ];
""", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(found)} ranges", file=sys.stderr)


if __name__ == "__main__":
    main()

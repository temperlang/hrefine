"""Writes src/wpt-search-params-tests.temper.md from web-platform-tests'
data-driven search parameter cases (tests/wpt/urlencoded-parser.any.js and
urlsearchparams-sort.any.js, vendored at the commit NOTICE names).

    uv run scripts/wpt_search_params_tests.py

Each file starts with an array literal of cases, which Node reads (as
JavaScript, since it isn't JSON), so this needs `node`. The rest of each
file runs the cases through browser APIs; the Temper test does what its
`URLSearchParams` and `URL` parts do. Cases with unpaired surrogates are
left out, and counted.
"""

import json
import subprocess
from pathlib import Path

from wpt_tests import literal, scalar_only

ROOT = Path(__file__).resolve().parent.parent
WPT = ROOT / "tests" / "wpt"
OUT = ROOT / "src" / "wpt-search-params-tests.temper.md"


def cases(name: str) -> list:
    """The array literal at the start of a test file, read by Node."""
    text = (WPT / name).read_text(encoding="utf-8")
    array = text[: text.index("].forEach(") + 1]
    run = subprocess.run(["node", "-e", f"process.stdout.write(JSON.stringify({array}))"],
                         capture_output=True, encoding="utf-8", check=True)
    return json.loads(run.stdout)


def rows(data: list) -> tuple[list[str], int]:
    """Each case as one list literal: the input, then each pair's name and value."""
    out, skipped = [], 0
    for case in data:
        strings = [case["input"]] + [s for pair in case["output"] for s in pair]
        if not scalar_only(*strings):
            skipped += 1
            continue
        out.append("        [" + ", ".join(literal(s) for s in strings) + "],")
    return out, skipped


def main() -> None:
    parse, parse_skipped = rows(cases("urlencoded-parser.any.js"))
    sort, sort_skipped = rows(cases("urlsearchparams-sort.any.js"))
    skipped = parse_skipped + sort_skipped
    OUT.write_text(f"""# Web Platform Tests: Search Parameters

Generated by `scripts/wpt_search_params_tests.py` from web-platform-tests'
`url/urlencoded-parser.any.js` and `url/urlsearchparams-sort.any.js` (see
NOTICE); don't edit by hand. {skipped} cases are left out, since their
strings hold unpaired surrogates, which Temper strings can't.

Each case is a list: the input, then the name and value of each pair it
must give, in order.

    let pairsText(pairs: List<Pair<String, String>>): String {{
      pairs.join(", ") {{ (p: Pair<String, String>): String => "${{p.key}}=${{p.value}}" }}
    }}

    let expectedText(c: List<String>): String {{
      let out = new ListBuilder<String>();
      for (var k = 1; k + 1 < c.length; k += 2) {{
        out.add("${{c[k]}}=${{c[k + 1]}}");
      }}
      out.toList().join(", ") {{ s => s }}
    }}

{len(parse)} inputs, parsed as `application/x-www-form-urlencoded`, by
`new UrlSearchParams(input)`.

    test("Form-urlencoded parsing: web-platform-tests' urlencoded-parser.any.js") {{
      let wrong = new ListBuilder<String>();
      for (let c of parseCases()) {{
        let actual = pairsText(new UrlSearchParams(c[0]).entries());
        if (actual != expectedText(c)) {{
          wrong.add("${{c[0]}}: ${{actual}}");
        }}
      }}
      assert(wrong.isEmpty) {{ wrong.toList().join("; ") {{ s => s }} }};
    }}

    let parseCases(): List<List<String>> {{
      [
{chr(10).join(parse)}
      ]
    }}

{len(sort)} inputs, parsed and sorted, both on their own and as a URL's
query, then read back from the URL's `search`.

    test("Sorting: web-platform-tests' urlsearchparams-sort.any.js") {{
      let wrong = new ListBuilder<String>();
      for (let c of sortCases()) {{
        let params = new UrlSearchParams(c[0]);
        params.sort();
        let actual = pairsText(params.entries());
        if (actual != expectedText(c)) {{
          wrong.add("${{c[0]}}: ${{actual}}");
        }}
        let url = parseUrl("?${{c[0]}}", "https://example/") orelse panic();
        let fromUrl = url.searchParams;
        fromUrl.sort();
        let sorted = url.withSearchParams(fromUrl);
        let again = pairsText(new UrlSearchParams(sorted.search).entries());
        if (again != expectedText(c)) {{
          wrong.add("${{c[0]}} in a URL: ${{again}}");
        }}
      }}
      let empty = parseUrl("http://example.com/?") orelse panic();
      let none = empty.searchParams;
      none.sort();
      let emptied = empty.withSearchParams(none);
      if (emptied.href != "http://example.com/" || emptied.search != "") {{
        wrong.add("sorting no parameters leaves ${{emptied.href}}");
      }}
      assert(wrong.isEmpty) {{ wrong.toList().join("; ") {{ s => s }} }};
    }}

    let sortCases(): List<List<String>> {{
      [
{chr(10).join(sort)}
      ]
    }}
""", encoding="utf-8")
    print(f"Wrote {len(parse)} parsing and {len(sort)} sorting cases ({skipped} left out) to "
          f"{OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

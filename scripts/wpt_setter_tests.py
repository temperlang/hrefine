"""Writes src/wpt-setter-tests.temper.md from web-platform-tests' setter
cases (tests/wpt/setters_tests.json, vendored at the commit NOTICE names).

    uv run scripts/wpt_setter_tests.py

Each case parses a URL, sets one part with the matching `with` method
(`withHost` for `host`, and so on), and checks the getters the case
gives. Cases with unpaired surrogates, which Temper strings can't hold,
are left out, and counted.
"""

import json
from pathlib import Path

from wpt_tests import literal, scalar_only

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tests" / "wpt" / "setters_tests.json"
OUT = ROOT / "src" / "wpt-setter-tests.temper.md"
GETTERS = ["href", "origin", "protocol", "username", "password", "host", "hostname", "port",
           "pathname", "search", "hash"]
CHUNK = 100


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    rows, skipped = [], 0
    for part, cases in data.items():
        if part == "comment":
            continue
        for case in cases:
            expected = case["expected"]
            strings = [case["href"], case["new_value"], *expected.values()]
            if not scalar_only(*strings):
                skipped += 1
                continue
            values = [part, case["href"], case["new_value"]]
            for g in GETTERS:
                values += ["y", expected[g]] if g in expected else ["n", ""]
            rows.append("      cases.addAll([" + ", ".join(literal(v) for v in values) + "]);")
    stride = 3 + 2 * len(GETTERS)
    setters = "\n".join(
        f'        "{p}" -> url.with{p[0].upper()}{p[1:]}(value);' for p in data if p not in ("comment", "href"))
    getters = "\n".join(f'        "{g}" -> url.{g};' for g in GETTERS)
    chunks = [
        f"""
    let addSetterCases{k}(cases: ListBuilder<String>): Void {{
{chr(10).join(rows[start:start + CHUNK])}
    }}
""" for k, start in enumerate(range(0, len(rows), CHUNK))]
    OUT.write_text(f"""# Web Platform Tests: Setters

Generated by `scripts/wpt_setter_tests.py` from web-platform-tests'
`url/resources/setters_tests.json` (see NOTICE); don't edit by hand.

{len(rows)} cases, each parsing a URL, setting one part with its `with`
method, and checking the parts the case gives, and that its [strict
form](strict.temper.md) is RFC 3986 and means the same URL. {skipped} cases are left
out, since their strings hold unpaired surrogates, which Temper strings
can't. The test reports every case that differs.

Each case is {stride} strings: the part to set, the URL, and the new
value; then, for each of {", ".join(GETTERS[:-1])}, and {GETTERS[-1]},
`y` and the value it must have, or `n` and nothing.

    let setPart(url: Url, part: String, value: String): Url throws Bubble {{
      when (part) {{
        "href" -> url.withHref(value);
{setters}
        else -> panic();
      }}
    }}

    let getPart(url: Url, part: String): String {{
      when (part) {{
{getters}
        else -> panic();
      }}
    }}

    test("WHATWG URL setters: web-platform-tests' setters_tests.json") {{
      let data = setterTestData();
      let stride = {stride};
      let getters = [{", ".join(f'"{g}"' for g in GETTERS)}];
      var cases = 0;
      var wrong = 0;
      let examples = new ListBuilder<String>();
      for (var i = 0; i < data.length; i += stride) {{
        cases += 1;
        let part = data[i];
        let url = parseUrl(data[i + 1]) orelse panic();
        let changed: Url? = setPart(url, part, data[i + 2]) orelse null;
        var problem = "";
        if (changed == null) {{
          problem = "bubbled";
        }} else {{
          problem = strictProblem(changed);
          for (var g = 0; problem == "" && g < getters.length; g += 1) {{
            let at = i + 3 + 2 * g;
            if (data[at] == "y") {{
              let actual = getPart(changed, getters[g]);
              if (actual != data[at + 1]) {{
                problem = "${{getters[g]}} is ${{actual}}, not ${{data[at + 1]}}";
              }}
            }}
          }}
        }}
        if (problem != "") {{
          wrong += 1;
          if (examples.length < 10) {{
            examples.add("${{data[i + 1]}} with ${{part}} ${{data[i + 2]}}: ${{problem}}");
          }}
        }}
      }}
      assert(wrong == 0) {{
        "${{wrong.toString()}} of ${{cases.toString()}} cases differ, such as: ${{examples.toList().join("; ") {{ e => e }}}}"
      }}
    }}

The data, built in chunks, which keeps each function small enough for
the JVM.

    let setterTestData(): List<String> {{
      let cases = new ListBuilder<String>();
{chr(10).join(f"      addSetterCases{k}(cases);" for k in range(len(chunks)))}
      cases.toList()
    }}
{"".join(chunks)}""", encoding="utf-8")
    print(f"Wrote {len(rows)} cases ({skipped} left out) to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
